def selected_count(rows: list[dict[str, str]], key: str, value: str | None = None) -> int:
    pairs = set()
    for row in rows:
        if value is not None and row[key] != value:
            continue
        if row.get("signal_classification") == "retained" and row.get("selected_direction"):
            pairs.add((row.get("target_taxon") or row.get("taxon_key", ""), row["selected_direction"]))
    return len(pairs)


