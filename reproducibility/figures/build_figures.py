def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def save_figure(fig: plt.Figure, stem: str, *, line_art: bool = False) -> list[Path]:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    paths: list[Path] = []
    for extension in ("pdf", "svg", "png"):
        path = OUTPUT_DIR / f"{stem}.{extension}"
        fig.savefig(path, dpi=600 if extension == "png" else None)
        paths.append(path)
    tif_path = OUTPUT_DIR / f"{stem}.tif"
    tif_dpi = 1200 if line_art else 600
    fig.savefig(tif_path, dpi=tif_dpi, pil_kwargs={"compression": "tiff_lzw"})
    with Image.open(tif_path) as handle:
        handle.convert("RGB").save(tif_path, format="TIFF", compression="tiff_lzw", dpi=(tif_dpi, tif_dpi))
    paths.append(tif_path)
    plt.close(fig)
    return paths


def box(ax, xy, width, height, text, *, edge=DARK, face="white", weight="normal", size=7.0) -> None:
    ax.add_patch(Rectangle(xy, width, height, facecolor=face, edgecolor=edge, linewidth=0.8))
    ax.text(xy[0] + width / 2, xy[1] + height / 2, text, ha="center", va="center",
            color=DARK, fontsize=size, fontweight=weight, linespacing=1.15)


def arrow(ax, start, end, *, colour=DARK, style="-|>") -> None:
    ax.add_patch(FancyArrowPatch(start, end, arrowstyle=style, mutation_scale=9,
                                linewidth=0.9, color=colour, shrinkA=0, shrinkB=0))


