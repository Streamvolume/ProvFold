def write_manifest(outputs: list[Path]) -> None:
    manifest = {
        "generated_by": Path(__file__).name,
        "manual_postprocessing": "none",
        "inputs": [
            {"asset": name, "path": path.name, "sha256": sha256(path)}
            for name, path in INPUTS.items()
        ],
        "outputs": [
            {"path": path.name, "size_bytes": path.stat().st_size, "sha256": sha256(path)}
            for path in outputs
        ],
    }
    (OUTPUT_DIR / "figure_provenance_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


